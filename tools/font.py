#!/usr/bin/env python3
"""Rasterize TrueType fonts into the C source used by the game.

Usage: font.py output.c small.ttf:size medium.ttf:size large.ttf:size title.ttf:size

The fonts become FONT_SMALL, FONT_MEDIUM, FONT_LARGE and FONT_TITLE. Glyphs
cover ASCII and the Latin-1 letters, except for the title font, which only
has the capital letters. They have 2 bits per pixel of coverage so they can
be antialiased against the palette. Needs Pillow.
"""

import sys

from PIL import ImageFont

NAMES = ["small", "medium", "large", "title"]
CHARS = [c for c in range(0x20, 0x7F)] + [c for c in range(0xC0, 0x100)]
TITLE_CHARS = [c for c in range(ord("A"), ord("Z") + 1)]


def rasterize(path, size, chars):
    font = ImageFont.truetype(path, size)
    cap_height = -font.getbbox("H", anchor="ls")[1]
    glyphs = {}
    pixels = bytearray()

    for code in chars:
        char = chr(code)
        mask, (x, y) = font.getmask2(char, mode="L", anchor="ls")
        w, h = mask.size
        levels = [round(v * 3 / 255) for v in bytes(mask)]

        offset = len(pixels)
        packed = bytearray((len(levels) + 3) // 4)
        for i, level in enumerate(levels):
            packed[i // 4] |= level << (i % 4 * 2)
        pixels += packed

        advance = round(font.getlength(char))
        glyphs[code] = (x, y, w, h, advance, offset)

    if len(pixels) > 0xFFFF:
        sys.exit(f"{path}:{size}: too much pixel data for 16-bit offsets")
    return cap_height, glyphs, pixels


def main():
    if len(sys.argv) != 2 + len(NAMES):
        sys.exit(__doc__)

    with open(sys.argv[1], "w", encoding="ascii") as out:
        out.write("// Generated by tools/font.py from the Mitr font, do not edit.\n")
        out.write("// Mitr is licensed under the SIL Open Font License, see OFL.txt.\n")
        out.write("// " + " ".join(arg.split("/")[-1] for arg in sys.argv[2:]) + "\n\n")
        out.write('#include "font.h"\n')

        caps = []
        for name, arg in zip(NAMES, sys.argv[2:]):
            path, size = arg.rsplit(":", 1)
            chars = TITLE_CHARS if name == "title" else CHARS
            cap_height, glyphs, pixels = rasterize(path, int(size), chars)
            caps.append(cap_height)

            out.write(f"\nstatic const uint8_t {name}_pixels[] = {{\n")
            out.writelines(
                "    " + ", ".join(f"0x{b:02x}" for b in pixels[i : i + 16]) + ",\n"
                for i in range(0, len(pixels), 16)
            )
            out.write("};\n\n")

            out.write(f"static const struct glyph {name}_glyphs[256] = {{\n")
            out.writelines(
                f"    [0x{code:02x}] = {{ {x}, {y}, {w}, {h}, {advance}, {offset} }},\n"
                for code, (x, y, w, h, advance, offset) in glyphs.items()
            )
            out.write("};\n")

        out.write("\nconst struct font fonts[] = {\n")
        for name, cap_height in zip(NAMES, caps):
            out.write(
                f"    [FONT_{name.upper()}] = {{ {cap_height}, {name}_glyphs, {name}_pixels }},\n"
            )
        out.write("};\n")


if __name__ == "__main__":
    main()
