#!/usr/bin/env python3
"""Turn the license files into a C source file, so they ship inside the ROM.

Usage: licenses.py output.c file...

Many of the licenses ask for their notices in every copy, and a ROM often
travels without the rest of the repository.
"""

import sys


def c_string(line):
    # Octal escapes stop after three digits, so they can't swallow what follows.
    out = ""
    for byte in line.encode("utf-8"):
        if byte in (0x22, 0x5C):
            out += "\\" + chr(byte)
        elif 0x20 <= byte < 0x7F and byte != 0x3F:
            out += chr(byte)
        else:
            out += f"\\{byte:03o}"
    return f'"{out}"'


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)

    with open(sys.argv[1], "w", encoding="ascii") as out:
        out.write("// Generated by tools/licenses.py, do not edit.\n\n")
        out.write("const char licenses[] =\n")
        for path in sys.argv[2:]:
            with open(path, encoding="utf-8") as f:
                out.writelines(f"    {c_string(line)}\n" for line in f)
        out.write("    ;\n")


if __name__ == "__main__":
    main()
