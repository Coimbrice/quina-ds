#!/usr/bin/env python3
"""Convert the word lists into a C source file for the ROM.

Usage: wordlist.py answers.txt allowed.txt output.c

Every word is stored without accents, sorted, so guesses can be found with a
binary search. Words that have accents also get their display form, encoded
in Latin-1 to match the font. Answers are included in the allowed words and
their order is shuffled once with a fixed seed for the daily challenge.
"""

import sys
import unicodedata

WORD_LEN = 5
SEED = 0x5157494E


def normalize(word):
    decomposed = unicodedata.normalize("NFD", word)
    return "".join(c for c in decomposed if not unicodedata.combining(c))


def read_words(path):
    words = []
    with open(path, encoding="utf-8") as f:
        for line_number, line in enumerate(f, 1):
            word = unicodedata.normalize("NFC", line.strip().lower())
            if not word:
                continue
            plain = normalize(word)
            if len(plain) != WORD_LEN or not all("a" <= c <= "z" for c in plain):
                sys.exit(f"{path}:{line_number}: invalid word '{word}'")
            words.append(word)
    return words


def shuffle(items, seed):
    # A fixed xorshift32 instead of Python's random module, so the daily
    # order never depends on the Python version.
    state = seed
    for i in range(len(items) - 1, 0, -1):
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        j = state % (i + 1)
        items[i], items[j] = items[j], items[i]


def c_string(text):
    # Octal escapes stop after three digits, unlike hex ones, so a letter
    # right after an accented one is never read as part of the escape.
    return '"' + "".join(chr(b) if b < 0x80 else f"\\{b:03o}" for b in text.encode("latin-1")) + '"'


def write_array(out, values):
    for i in range(0, len(values), 12):
        out.write("    " + ", ".join(str(n) for n in values[i : i + 12]) + ",\n")


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)

    answers = read_words(sys.argv[1])
    allowed = read_words(sys.argv[2])

    # Answers come last so their accented form wins over the allowed list.
    display = {}
    for word in allowed + answers:
        display[normalize(word)] = word

    words = sorted(display)
    if len(words) > 0xFFFF:
        sys.exit("too many words for 16-bit indices")
    index = {word: i for i, word in enumerate(words)}

    order = sorted({index[normalize(word)] for word in answers})
    shuffle(order, SEED)

    accented = [i for i, word in enumerate(words) if display[word] != word]

    with open(sys.argv[3], "w", encoding="ascii") as out:
        out.write("// Generated by tools/wordlist.py, do not edit.\n\n")
        out.write('#include "words.h"\n\n')

        out.write(f"const int word_count = {len(words)};\n")
        out.write("const char word_list[] =\n")
        for word in words:
            out.write(f'    "{word}"\n')
        out.write("    ;\n\n")

        out.write(f"const int answer_count = {len(order)};\n")
        out.write("const uint16_t answer_order[] = {\n")
        write_array(out, order)
        out.write("};\n\n")

        out.write(f"const int accented_count = {len(accented)};\n")
        out.write("const uint16_t accented_index[] = {\n")
        write_array(out, accented)
        out.write("};\n")
        out.write('const char accented_text[] =\n    ""\n')
        out.writelines(f"    {c_string(display[words[i]])}\n" for i in accented)
        out.write("    ;\n")


if __name__ == "__main__":
    main()
